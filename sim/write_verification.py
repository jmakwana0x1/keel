"""Render data/verification.md from the machine-readable transcript data/phase1_mutations.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Python twins, from data/phase0_quoter_diff.json (mutations run on the replayed mainnet books against QuoterV2)
PY = {
    "amount1 rounds down": "fails every **up** walk (token1 in), no down walk",
    "amount0 rounds down": "fails every **down** walk (token0 in), no up walk",
    "skip word-boundary steps": "fails 69 of 89 walks containing a word-boundary step, and **no other walk**; the 20 that "
                                "keep passing are the ≤1-unit cases where one round-up equals two",
}


def main():
    r = json.loads((ROOT / "data" / "phase1_mutations.json").read_text())
    q = json.loads((ROOT / "data" / "phase0_quoter_diff.json").read_text())["mutations_on_same_sample"]
    muts = [k for k in r if k not in ("baseline", "after_restore")]
    tests = list(r["baseline"])
    L = ["# Verification transcript", "",
         "Machine-generated by `sim/write_verification.py` from `data/phase1_mutations.json`, which `sim/mutate_solidity.py` "
         "writes. Every planted edit is applied at the one site where that defect could be introduced, the anchor is asserted "
         "to occur exactly once, every Phase 1 suite is run (fuzz at 100 runs), and the file is restored byte-for-byte with a "
         "hash check. A layer that fails everything tells less than one that fails selectively: the **keeps passing** column "
         "is evidence.", "",
         "## Phase 1 — the meter: the three Phase 0 mutations, ported to Solidity", "",
         "| Mutation | Site |", "|---|---|",
         "| amount1 rounds down | `lib/v4-core/src/libraries/SqrtPriceMath.sol` `getAmount1Delta`: round-up term forced to 0 |",
         "| amount0 rounds down | same file, `getAmount0Delta`: floor branch taken |",
         "| skip word-boundary steps | `src/adapters/V4TickSource.sol`: both search directions skip empty words instead of "
         "stopping at the boundary |", "",
         "| Test | baseline | " + " | ".join(muts) + " | after restore |", "|---|---|" + "---|" * len(muts) + "---|"]
    for t in tests:
        L.append(f"| `{t}` | {r['baseline'][t]} | " + " | ".join(
            ("**FAIL**" if r[m].get(t) == "FAIL" else r[m].get(t, "—")) for m in muts) + f" | {r['after_restore'][t]} |")
    L += ["", "### Localisation, against the Python twins", ""]
    for m in muts:
        failing = [t for t in tests if r[m].get(t) == "FAIL"]
        L.append(f"- **{m}** — Solidity: {len(failing)} of {len(tests)} tests fail "
                 f"({', '.join('`' + t.split('.')[-1] + '`' for t in failing) or 'none'}). Python twin (Phase 0, on real "
                 f"books vs QuoterV2): {PY[m]} ({q[m]['failing']} walks failing).")
    L += ["", "### Findings about the port", "",
          "1. **Only the Python reference detects a rounding defect inside v4-core.** The rounding mutations sit in "
          "`SqrtPriceMath`, which the PoolManager shares. On the side where the PoolManager differential is a pure value "
          "comparison (amount1: up walks; amount0: down walks), the mutated pool and the mutated meter agree, and the test "
          "**keeps passing**. The Python reference shares no code with v4-core and fails on exactly that side, matching "
          "its Phase 0 twin's direction. This is the case for two references in one line.",
          "2. **The PoolManager differential's failures under those mutations are collateral, not detection.** It fails "
          "on the *opposite* side by **reverting**: the same rounding governs liquidity deposits, so the pool takes too "
          "little of one token, and paying that token out underflows the ERC-20 balance (`Panic(0x11)` inside "
          "`transfer`). Reproduced in isolation with `testFuzz_meterMatchesPool_down` under `amount1 rounds down`. A "
          "suite that only had the PoolManager reference would have reported this mutation as caught, for the wrong "
          "reason (rule 6).",
          "3. **The word-boundary mutation is seen by both differentials in both directions**, because it sits in our "
          "adapter, not in shared code. `SaturationReproductionTest` correctly keeps passing: it reads books through "
          "`BookTickSource`, not the mutated `V4TickSource`. The Python twin localised to boundary walks only; the "
          "Solidity suites are per-direction, not per-walk, so they cannot show that finer localisation.",
          "4. **Suites that keep passing under every mutation** (`DepthBoundary`, `Contribution`, the unit tests, "
          "`allTiers_withGap`) test properties that are invariant to these defects. `cappedWalk*` and the verdict table "
          "test decisions, not amounts. `Contribution` compares two walks that share the mutated math. For "
          "`allTiers_withGap` under the boundary mutation the reason is structural: its word boundaries fall only inside "
          "its voids, where liquidity is zero and splitting a step changes nothing. Under the rounding mutations the "
          "reason is **not established**; the likely one is that its walks never drain a side of the pool, so finding "
          "2's deposit shortfall never surfaces. None of these suites is the line of defence for these defects, and "
          "none claims to be."]
    (ROOT / "data" / "verification.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
